fn at_line(s: &str) -> String {
    match AtTime::parse(s) {
        Ok(t) => format!("{s:?} -> {}", t.describe()),
        Err(e) => format!("{s:?} -> Err({})", e.message),
    }
}

fn epoch_line(s: &str) -> String {
    match rfc3339_to_epoch(s) {
        Ok(v) => format!("{s:?} -> {v}"),
        Err(e) => format!("{s:?} -> Err({})", e.message),
    }
}

/// `pki::parse_time` and both X.509 time encoders (UTCTime 1950–2049 / GeneralizedTime) of its result.
fn der_line(s: &str) -> String {
    match pki::parse_time(Some(s)) {
        Ok(t) => format!(
            "{s:?} -> {} | {} | {}",
            rfc3339(t),
            hex(&derw::time(t)),
            hex(&derw::gentime(t))
        ),
        Err(e) => format!("{s:?} -> Err({})", e.message),
    }
}

fn lines() -> Vec<String> {
    let mut v = vec![];
    v.extend(AT_INPUTS.iter().map(|s| at_line(s)));
    v.extend(AT_INPUTS.iter().map(|s| epoch_line(s)));
    v.extend(
        AT_INPUTS
            .iter()
            .filter(|s| !s.trim().is_empty() && !s.trim().eq_ignore_ascii_case("now"))
            .map(|s| der_line(s)),
    );
    v.extend(
        EPOCHS
            .iter()
            .map(|e| format!("{e} -> {}", epoch_to_rfc3339(*e))),
    );
    v.extend(
        PRINTED
            .iter()
            .map(|s| format!("{s:?} -> {:?}", printed_time_to_rfc3339(s))),
    );
    v.extend(
        GENTIMES
            .iter()
            .map(|s| format!("{s:?} -> {:?}", generalized_time(s.as_bytes()))),
    );
    v
}

#[test]
fn golden_time_conversions() {
    let got = lines();
    assert_eq!(got.len(), WANT.len());
    for (g, w) in got.iter().zip(WANT) {
        assert_eq!(g, w);
    }
}

/// The wall-clock forms keep their shape (second precision, `Z`) and agree with each other.
#[test]
fn wall_clock_shapes() {
    let n = now_rfc3339();
    assert_eq!(n.len(), 20, "{n}");
    assert!(n.ends_with('Z') && &n[10..11] == "T", "{n}");
    let t = pki::now();
    let a = rfc3339(t);
    assert_eq!(a.len(), 20, "{a}");
    let e = rfc3339_to_epoch(&a).unwrap();
    assert_eq!(epoch_to_rfc3339(e), a);
    assert!((rfc3339_to_epoch(&n).unwrap() - e).abs() <= 2);
    assert_eq!(rfc3339(pki::parse_time(None).unwrap()).len(), 20);
    assert_eq!(rfc3339(pki::parse_time(Some(" now ")).unwrap()).len(), 20);
}

